#!/usr/bin/env python3
"""Configurable Co-Architect Workspace Lifecycle Hook Entrypoint (`workspace_hooks.py`).

Loads `state/workspace_config.json` generated by `bootstrap.py build` and enforces:
1. `[<Architect> Debug Mode]` Core Architecture Lock across file writes and shell commands.
2. `human-voice.md` Preventive Anti-Slop & Invisible Unicode / Prompt-Injection Gates.
3. CaMeL untrusted-input taint & Subagent Model Tiering (`flash` / `pro` / gated `inherit`).
4. `SessionStart` state-cap, staleness, and `SYSTEM_PROMPT.md` <-> `GEMINI.md` parity checks.
5. `PostToolUse` SHA-256 hash-chained `state/audit_log.jsonl` provenance logging.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
from typing import Any

_SCRIPT_DIR = Path(__file__).resolve().parent
if str(_SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPT_DIR))

from core_hooks import (  # noqa: E402
    audit_state_files,
    dispatch_hook_cli,
    evaluate_base_pre_tool_use,
    handle_post_tool_use as _core_handle_post_tool_use,
    lint_markdown_slop,
    lint_security_payload,
    resolve_workspace_root,
)

WORKSPACE_ROOT = resolve_workspace_root(__file__)

FALLBACK_LOCKED_REL_PATHS: tuple[str, ...] = (
    "SYSTEM_PROMPT.md",
    "AGENTS.md",
    "CLAUDE.md",
    "GEMINI.md",
    ".claude/settings.json",
    ".cursor/rules/coarchitect.mdc",
    "state/workspace_config.json",
    ".agents/hooks.json",
    ".agents/rules/human-voice.md",
    ".agents/rules/state-hydration.md",
    ".agents/scripts/core_hooks.py",
    ".agents/scripts/workspace_hooks.py",
    ".agents/scripts/audit_log.py",
    ".agents/skills/council/SKILL.md",
    ".agents/skills/council/references/personas.md",
    ".agents/skills/iterate/SKILL.md",
    ".agents/skills/iterate/references/critic_panels.md",
    ".agents/skills/iterate/scripts/iterate_stage.py",
)

FALLBACK_STATE_SPECS: list[dict[str, Any]] = [
    {"label": "active_sprint.md", "max_lines": 100, "max_bytes": 8000, "max_stale_days": 14},
    {"label": "operator_profile.md", "max_lines": 100, "max_bytes": 8000, "max_stale_days": None},
    {"label": "routing_matrix.md", "max_lines": 100, "max_bytes": 8000, "max_stale_days": None},
    {"label": "archive_decisions.md", "max_lines": 150, "max_bytes": 16000, "max_stale_days": None},
]


def load_workspace_config(ws_root: str = WORKSPACE_ROOT) -> dict[str, Any]:
    cfg_path = os.path.join(ws_root, "state", "workspace_config.json")
    if os.path.isfile(cfg_path):
        try:
            with open(cfg_path, "r", encoding="utf-8") as f:
                data = json.load(f)
                if isinstance(data, dict):
                    return data
        except Exception:
            pass
    return {
        "architect_name": "Architect",
        "debug_phrase": "[Architect Debug Mode]",
        "timezone": None,
        "kortex_account": "",
        "default_notebook_id": "",
        "locked_rel_paths": list(FALLBACK_LOCKED_REL_PATHS),
        "state_files_to_audit": FALLBACK_STATE_SPECS,
    }


def handle_pre_tool_use(payload: dict[str, Any]) -> dict[str, Any]:
    cfg = load_workspace_config(WORKSPACE_ROOT)
    rel_list = tuple(str(x) for x in (cfg.get("locked_rel_paths") or FALLBACK_LOCKED_REL_PATHS))
    locked_paths = {
        os.path.normcase(os.path.realpath(os.path.join(WORKSPACE_ROOT, *rel.split("/"))))
        for rel in rel_list
    }
    return evaluate_base_pre_tool_use(
        payload,
        workspace_root=WORKSPACE_ROOT,
        locked_paths=locked_paths,
        locked_rel_paths=rel_list,
        debug_phrase=str(cfg.get("debug_phrase") or "[Architect Debug Mode]"),
        default_kortex_account=str(cfg.get("kortex_account") or ""),
        default_notebook_id=str(cfg.get("default_notebook_id") or ""),
    )


def handle_post_tool_use(payload: dict[str, Any]) -> dict[str, Any]:
    cfg = load_workspace_config(WORKSPACE_ROOT)
    return _core_handle_post_tool_use(
        payload,
        workspace_root=WORKSPACE_ROOT,
        tz_name=cfg.get("timezone"),
    )


def handle_session_start(_payload: dict[str, Any]) -> dict[str, Any]:
    cfg = load_workspace_config(WORKSPACE_ROOT)
    raw_specs = cfg.get("state_files_to_audit") or FALLBACK_STATE_SPECS
    specs: list[tuple[str, str, int, int, int | None]] = []
    for item in raw_specs:
        if isinstance(item, dict) and item.get("label"):
            lbl = str(item["label"])
            specs.append(
                (
                    lbl,
                    os.path.join(WORKSPACE_ROOT, "state", lbl),
                    int(item.get("max_lines") or 100),
                    int(item.get("max_bytes") or 8000),
                    int(item["max_stale_days"]) if item.get("max_stale_days") is not None else None,
                )
            )
    return audit_state_files(
        specs,
        workspace_root=WORKSPACE_ROOT,
        alert_prefix="STATE AUDIT ALERT",
        tz_name=cfg.get("timezone"),
    )


def check_files(
    paths: list[str],
    *,
    staged: bool = False,
    ws_root: str = WORKSPACE_ROOT,
) -> int:
    """Enforce core lock, hidden-Unicode security, and anti-slop rules for CLI/git hooks."""
    candidates: list[str] = list(paths)
    if staged:
        proc = subprocess.run(
            ["git", "-C", ws_root, "diff", "--cached", "--name-only", "--diff-filter=ACMR"],
            capture_output=True,
            text=True,
            check=False,
        )
        if proc.returncode == 0:
            for line in proc.stdout.splitlines():
                trimmed = line.strip()
                if trimmed and trimmed not in candidates:
                    candidates.append(trimmed)

    if not candidates:
        return 0

    cfg = load_workspace_config(ws_root)
    rel_list = tuple(str(x) for x in (cfg.get("locked_rel_paths") or FALLBACK_LOCKED_REL_PATHS))
    locked_paths = {
        os.path.normcase(os.path.realpath(os.path.join(ws_root, *rel.split("/"))))
        for rel in rel_list
    }
    locked_rel_norm = {rel.replace("\\", "/").lstrip("./") for rel in rel_list}
    debug_override = os.environ.get("COARCHITECT_DEBUG", "").strip() == "1"

    violations: list[str] = []
    ws_real = os.path.realpath(ws_root)
    for raw_p in candidates:
        p = Path(raw_p)
        if not p.is_absolute():
            p = Path(ws_root) / raw_p
        resolved_str = os.path.realpath(str(p))
        try:
            rel_posix = os.path.relpath(resolved_str, ws_real).replace("\\", "/")
        except ValueError:
            rel_posix = raw_p.replace("\\", "/").lstrip("./")
        norm_resolved = os.path.normcase(resolved_str)

        if (norm_resolved in locked_paths or rel_posix in locked_rel_norm) and not debug_override:
            violations.append(
                f"{rel_posix}: Core Architecture Lock violation (set COARCHITECT_DEBUG=1 to override)."
            )

        if not p.is_file():
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue

        is_state_cache = rel_posix.startswith("state/")
        sec_err = lint_security_payload(rel_posix, text, check_stored_injection=is_state_cache)
        if sec_err:
            violations.append(f"{rel_posix}: {sec_err}")

        if rel_posix.lower().endswith(".md"):
            slop_err = lint_markdown_slop(str(p), text)
            if slop_err:
                violations.append(f"{rel_posix}: {slop_err}")

    if violations:
        for msg in violations:
            sys.stderr.write(msg + "\n")
        sys.stderr.flush()
        return 1
    return 0


def main() -> None:
    if len(sys.argv) > 1 and sys.argv[1] == "check-files":
        args = sys.argv[2:]
        staged = "--staged" in args
        file_args = [a for a in args if a != "--staged"]
        sys.exit(check_files(file_args, staged=staged, ws_root=WORKSPACE_ROOT))

    cfg = load_workspace_config(WORKSPACE_ROOT)
    dispatch_hook_cli(
        workspace_root=WORKSPACE_ROOT,
        pre_handler=handle_pre_tool_use,
        post_handler=handle_post_tool_use,
        session_handler=handle_session_start,
        tz_name=cfg.get("timezone"),
    )


if __name__ == "__main__":
    main()
